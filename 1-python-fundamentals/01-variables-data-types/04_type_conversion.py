# Type Conversion

# String to Integer
age = "20"
age = int(age)

print(age)
print(type(age))


# Integer to Float
marks = 95
marks = float(marks)

print(marks)
print(type(marks))


# Integer to String
number = 100
number = str(number)

print(number)
print(type(number))


# String to Float
price = "99.99"
price = float(price)

print(price)
print(type(price))