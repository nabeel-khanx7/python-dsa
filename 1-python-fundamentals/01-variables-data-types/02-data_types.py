# Python Data Types

name = "Nabeel"          # str
age = 20                 # int
height = 5.11            # float
is_student = True        # bool

skills = ["Python", "C++", "AI/ML"]   # list
coordinates = (10, 20)                # tuple
languages = {"Python", "C++"}         # set
student = {
    "name": "Nabeel",
    "age": 20
}                                      # dict

nothing = None                         # NoneType


print(type(name))
print(type(age))
print(type(height))
print(type(is_student))
print(type(skills))
print(type(coordinates))
print(type(languages))
print(type(student))
print(type(nothing))